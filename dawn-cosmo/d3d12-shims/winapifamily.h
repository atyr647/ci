#pragma once
/* Desktop family with every partition enabled; the real header selects API sets for UWP/Xbox, which do not matter for a compile of Dawn's backend. */
#define WINAPI_PARTITION_DESKTOP 0x00000001
#define WINAPI_PARTITION_APP 0x00000002
#define WINAPI_PARTITION_PC_APP 0x00000002
#define WINAPI_PARTITION_PHONE_APP 0x00000004
#define WINAPI_PARTITION_SYSTEM 0x00000008
#define WINAPI_PARTITION_SERVER 0x00000010
#define WINAPI_PARTITION_GAMES 0x00000020
#define WINAPI_PARTITION_TV_APP 0x00000040
#define WINAPI_PARTITION_TV_TITLE 0x00000080
#define WINAPI_FAMILY_PC_APP 2
#define WINAPI_FAMILY_DESKTOP_APP 100
#define WINAPI_FAMILY WINAPI_FAMILY_DESKTOP_APP
#define WINAPI_PARTITION_ENABLED (WINAPI_PARTITION_DESKTOP | WINAPI_PARTITION_APP | WINAPI_PARTITION_SYSTEM | WINAPI_PARTITION_SERVER | WINAPI_PARTITION_GAMES)
#define WINAPI_FAMILY_PARTITION(Partitions) (!!((Partitions) & WINAPI_PARTITION_ENABLED))
#define WINAPI_FAMILY_ONE_PARTITION(Family, Partition) (WINAPI_FAMILY == (Family))
#define WINAPI_FAMILY_NOT_PARTITION(Partitions) (!WINAPI_FAMILY_PARTITION(Partitions))
