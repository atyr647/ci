#!/usr/bin/env python3
"""Writes a C file that defines do-nothing replacements (return nullptr) for the Dawn backend connectors named on the command line, so a link that supplies them never pulls
that backend's objects out of the archive. Looks the real symbol names up in the undefined symbols of the objects.
usage: gen_stubs.py <arch x86_64|aarch64> <objdir> <out.c> <backend> ..."""
import sys, subprocess, glob, re
arch, objdir, out, backends = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]
syms = subprocess.run(['llvm-nm', '-u'] + sorted(glob.glob(objdir + '/*.o')), capture_output=True, text=True).stdout.split()
body = ['/* generated by gen_stubs.py */']
for b in backends:
    pat = re.compile(r'^_ZN4dawn6native%d%s7ConnectE' % (len(b), b))
    found = sorted({s for s in syms if pat.match(s)})
    assert found, 'no Connect symbol for ' + b
    for s in found:
        if arch == 'x86_64':
            body.append('__asm__(".text\\n.globl %s\\n.type %s,@function\\n%s:\\n xorl %%eax,%%eax\\n ret\\n");' % (s, s, s))
        else:
            body.append('__asm__(".text\\n.globl %s\\n.type %s,%%function\\n%s:\\n mov x0, xzr\\n ret\\n");' % (s, s, s))
        print('stub', b, s)
open(out, 'w').write('\n'.join(body) + '\n')
