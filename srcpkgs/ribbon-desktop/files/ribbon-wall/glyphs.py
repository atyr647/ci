#!/usr/bin/env python3
"""glyphs.py FONT.ttf TEXT LETTERSPACING > NAME.glyphs   (build time)

Writes TEXT's outlines as data (a Tcl dict: advance, contours) for look.tcl's
"mark" layer, never run as code, so the
wallpaper wordmark is drawn by Tcl's own rasteriser (no font engine needed
at run time). Units: em = 1.0, baseline at y = 0, y down; quadratic curves
kept as "Q cx cy x y" so look.tcl can flatten them for the output's size.
The advance includes CSS letter-spacing (em units), trailing one included,
as CSS does.
"""
import sys
from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

font = TTFont(sys.argv[1]); text = sys.argv[2]; ls = float(sys.argv[3])
upm = font["head"].unitsPerEm; gs = font.getGlyphSet(); cmap = font.getBestCmap()
class Pen(BasePen):
    def __init__(self, gs, dx):
        super().__init__(gs); self.dx = dx; self.out = []; self.cur = []
    def p(self, pt): return f"{(pt[0] + self.dx) / upm:.5f} {-pt[1] / upm:.5f}"
    def _moveTo(self, pt): self.cur = ["M " + self.p(pt)]
    def _lineTo(self, pt): self.cur.append("L " + self.p(pt))
    def _qCurveToOne(self, c, pt): self.cur.append(f"Q {self.p(c)} {self.p(pt)}")
    def _curveToOne(self, a, b, pt): self.cur.append(f"L {self.p(pt)}")  # TrueType has none
    def _closePath(self): self.out.append(" ".join(self.cur)); self.cur = []
x = 0.0; contours = []
for ch in text:
    g = cmap[ord(ch)]; pen = Pen(gs, x); gs[g].draw(pen); contours += pen.out
    x += gs[g].width + ls * upm
print("# glyph outlines (data, read by look.tcl, never run), generated by glyphs.py from", sys.argv[1].split("/")[-1], repr(text))
print(f"advance {x / upm:.5f}")
print("contours {"); [print("\t{" + c + "}") for c in contours]; print("}")
