#!/bin/sh
# build/install/deps.sh - the dependencies report: what each Ribbon package needs, in base-neutral names.
#
#   build/install/deps.sh > dependencies.txt
#
# Read from each package's srcpkgs/PACKAGE/template (depends; makedepends and hostmakedepends for the packages
# build.sh compiles; distfiles; make_dirs, system_accounts, conf_files) and described with build/install/deps.map.
# A name a template declares that deps.map does not describe is an error, so the report never drops one.
set -eu
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
cd "$ROOT"
MAP=build/install/deps.map
OWN=$(for m in build/install/manifests/*.manifest; do basename "$m" .manifest; done)
THIRD="tkdnd tcl-unix-sockets mk4tcl font-jetbrains-mono ribbon-kernel"

field() { # PACKAGE VAR: the template's value of VAR, on one line
	(
		# shellcheck disable=SC1090
		set +eu; XBPS_CROSS_BASE=; . "srcpkgs/$1/template" >/dev/null 2>&1
		eval "printf '%s\n' \"\${$2:-}\"" | tr '\n\t' '  ' | tr -s ' ' | sed 's/^ //; s/ $//'
	)
}
describe() { # NAME: one report line, or an error for a name deps.map does not have
	n=$1
	for o in $OWN; do [ "$n" = "$o" ] && { printf '    %s | %s | void: %s\n' "$n" "Ribbon package (make install-$n)" "$n"; return 0; }; done
	line=$(awk -F'|' -v n="$n" '/^#/ { next } { k = $1; gsub(/^ +| +$/, "", k); if (k == n) { print; exit } }' "$MAP")
	[ -n "$line" ] || { echo "deps.sh: srcpkgs declare $n, which $MAP does not describe" >&2; exit 1; }
	neutral=$(echo "$line" | cut -d'|' -f2 | sed 's/^ *//; s/ *$//')
	why=$(echo "$line" | cut -d'|' -f3 | sed 's/^ *//; s/ *$//')
	for t in $THIRD; do [ "$n" = "$t" ] && why="$why; third-party, packaged by Ribbon (srcpkgs/$n), not built by make build"; done
	case $neutral in -*) neutral="(none: Void only)${neutral#-}" ;; esac
	printf '    %s | %s | void: %s\n' "$neutral" "$why" "$n"
}
section() { # TITLE NAMES...
	t=$1; shift
	[ $# -gt 0 ] || return 0
	echo "  $t:"
	for n in "$@"; do describe "$n"; done
}

echo "# Ribbon packages and what they need (generated by build/install/deps.sh from srcpkgs/*/template)"
echo "# each line: the dependency (base-neutral) | what it is needed for | void: the Void package name, as a hint"
for p in $OWN; do
	echo
	echo "== $p: $(field "$p" short_desc)"
	# shellcheck disable=SC2046
	section "runtime" $(field "$p" depends)
	if grep -q '@build/' "build/install/manifests/$p.manifest"; then
		# shellcheck disable=SC2046
		section "to build (make build)" $(field "$p" hostmakedepends) $(field "$p" makedepends)
	fi
	df=$(field "$p" distfiles)
	if [ -n "$df" ]; then
		echo "  third-party inputs (distfiles, not built here):"
		for d in $df; do echo "    $d"; done
	fi
	ex=$(sed -n 's/^external \([^ ]*\) \(.*\)/\/\1 (\2)/p' "build/install/manifests/$p.manifest")
	if [ -n "$ex" ]; then
		echo "  files of the package that make install does not provide (from the distfile above):"
		echo "$ex" | sed 's/^/    /'
	fi
	md=$(field "$p" make_dirs); sa=$(field "$p" system_accounts); cf=$(field "$p" conf_files)
	cx=$(field "$p" conflicts); rp=$(field "$p" replaces)
	[ -z "$sa" ] || echo "  system accounts to create: $sa (groups: $(field "$p" "_${sa#_}_pgroups"), home: $(field "$p" "_${sa#_}_homedir"))"
	[ -z "$md" ] || echo "  state directories (path mode owner group): $md"
	[ -z "$cf" ] || echo "  configuration files (keep local edits on upgrade): $cf"
	[ -z "$cx" ] || echo "  conflicts with: $cx; replaces: $rp"
done
echo
echo "== third-party packages Ribbon packages for Void (srcpkgs/), not built by make build"
for t in $THIRD; do
	echo "  $t $(field "$t" version): $(field "$t" short_desc)"
	# shellcheck disable=SC2046
	section "runtime" $(field "$t" depends)
done
