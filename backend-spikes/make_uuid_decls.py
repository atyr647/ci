#!/usr/bin/env python3
"""Generate uuid_decls.h: GCC ignores MIDL_INTERFACE("guid"), so __uuidof(IFoo) (used by IID_PPV_ARGS) has no value for Microsoft's DirectX-Headers interfaces.
Declare each GUID the way Wine's own generated headers do (__CRT_UUID_DECL), except for interfaces Wine's headers already declare.
usage: make_uuid_decls.py <out.h> <wine-windows-include-dir> <header-dir>..."""
import re, glob, sys, os
out, wine, dirs = sys.argv[1], sys.argv[2], sys.argv[3:]
declared = set()
shadowed = {os.path.basename(f) for d in dirs for f in glob.glob(os.path.join(d, '*.h'))}  # the include path picks these instead of Wine's
for f in glob.glob(os.path.join(wine, '*.h')):
    if os.path.basename(f) in shadowed: continue
    declared.update(re.findall(r'__CRT_UUID_DECL\s*\(\s*(\w+)\s*,', open(f, errors='ignore').read()))
pat = re.compile(r'MIDL_INTERFACE\("([0-9a-fA-F]{8})-([0-9a-fA-F]{4})-([0-9a-fA-F]{4})-([0-9a-fA-F]{2})([0-9a-fA-F]{2})-' + r'([0-9a-fA-F]{2})' * 6 + r'"\)\s*(?:DECLSPEC_NOVTABLE\s*)?(\w+)')
seen = {}
for d in dirs:
    for f in sorted(glob.glob(os.path.join(d, '*.h'))):
        for m in pat.finditer(open(f, errors='ignore').read()):
            g = m.groups()
            if g[11] not in declared: seen[g[11]] = g[:11]
lines = ['#pragma once', '/* generated by make_uuid_decls.py: __uuidof for interfaces declared with MIDL_INTERFACE, which GCC ignores */', '#include <guiddef.h>', '#ifdef __WINE_UUID_ATTR', 'extern "C++" {']
lines += [f'struct {n};' for n in sorted(seen)] + ['}']
lines += ['__CRT_UUID_DECL(%s, 0x%s, 0x%s, 0x%s, 0x%s, 0x%s, 0x%s, 0x%s, 0x%s, 0x%s, 0x%s, 0x%s)' % ((n,) + seen[n]) for n in sorted(seen)]
lines.append('#endif')
open(out, 'w').write('\n'.join(lines) + '\n')
print(len(seen), 'interfaces,', len(declared), 'already declared by Wine')
