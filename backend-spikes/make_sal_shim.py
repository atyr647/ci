#!/usr/bin/env python3
"""Generate sal_shim.h: SAL annotations (_In_, _Out_writes_(n), ...) as empty macros, plus IID_PPV_ARGS, for headers written for the Windows SDK.
usage: make_sal_shim.py <out.h> <header>..."""
import re, sys
out, files = sys.argv[1], sys.argv[2:]
names = set()
for f in files:
    for n in re.findall(r'\b(_[A-Z][A-Za-z0-9_]*_)\b', open(f, errors='ignore').read()):
        if not n.endswith(('_H_', 'KM_')) and not n.startswith('__'): names.add(n)
fn = lambda n: n in ('_Always_', '_Inexpressible_') or (any(k in n for k in ('reads', 'writes', 'count', 'Field_size', '_range', 'updates', 'bytebuffer')) and not n.endswith('_z_'))
lines = ['#pragma once', '/* generated by make_sal_shim.py: SAL annotations carry no code */']
for n in sorted(names):
    lines.append(f'#ifndef {n}\n#define {n}(...)\n#endif' if fn(n) else f'#ifndef {n}\n#define {n}\n#endif')
lines.append('''#ifdef __cplusplus
extern "C++" { template <typename T> void **IID_PPV_ARGS_Helper(T **pp) { return reinterpret_cast<void **>(pp); } }
#define IID_PPV_ARGS(pp) __uuidof(**(pp)), IID_PPV_ARGS_Helper(pp)
#endif''')
open(out, 'w').write('\n'.join(lines) + '\n'); print(len(names), 'annotations')
