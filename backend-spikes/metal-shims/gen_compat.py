#!/usr/bin/env python3
"""Generate cosmo_apple_compat.h for compiling Apple-SDK-dependent code (Dawn's Metal backend) with the Cosmopolitan toolchain.
Cosmopolitan supplies the C library (stdint.h, stddef.h, sys/types.h ... with Linux-style typedefs: uint64_t is unsigned long). Apple's SDK headers redefine the same
public types differently (unsigned long long), which would make Dawn's symbols mangle differently in these translation units than in the rest of Dawn. So: parse the
SDK's one-typedef-per-file headers in usr/include/sys/_types/, and pre-define the include guard of every header whose public typedef Cosmopolitan already provides.
usage: gen_compat.py <sdk-path> <out.h>"""
import re, sys, os, glob
sdk, out = sys.argv[1], sys.argv[2]
cosmo_has = set('''int8_t int16_t int32_t int64_t uint8_t uint16_t uint32_t uint64_t intptr_t uintptr_t intmax_t uintmax_t size_t ssize_t off_t wchar_t ptrdiff_t time_t clock_t
pid_t uid_t gid_t mode_t dev_t ino_t nlink_t useconds_t suseconds_t socklen_t blkcnt_t blksize_t fsblkcnt_t fsfilcnt_t id_t key_t 
va_list sigset_t wint_t wctype_t rsize_t errno_t timespec timeval fd_set pthread_t pthread_attr_t pthread_mutex_t pthread_mutexattr_t pthread_cond_t pthread_condattr_t
pthread_key_t pthread_once_t pthread_rwlock_t pthread_rwlockattr_t FILE fpos_t mbstate_t max_align_t'''.split())
guards, skipped, kept = [], [], []
for f in sorted(glob.glob(os.path.join(sdk, 'usr/include/sys/_types/_*.h'))):
    t = open(f, errors='ignore').read()
    g = re.search(r'#ifndef\s+(\w+)', t)
    names = set(re.findall(r'typedef\b[^;{}]*?\b(\w+)\s*;', t))
    names |= set(re.findall(r'\bstruct\s+(\w+)\s*\{', t))
    if g and names & cosmo_has:
        guards.append(g.group(1)); skipped.append(os.path.basename(f))
    else:
        kept.append(os.path.basename(f))
std_headers = """algorithm array atomic bit bitset cassert cctype cerrno cfloat chrono climits clocale cmath condition_variable cstdarg cstddef cstdint cstdio cstdlib
cstring ctime cwchar cwctype deque exception format forward_list functional initializer_list iomanip ios iosfwd iostream istream iterator limits list locale map memory
mutex new numeric optional ostream queue random ratio set shared_mutex span sstream stack stdexcept streambuf string string_view system_error thread tuple type_traits
typeindex unordered_map unordered_set utility variant vector""".split()
c_headers = """assert.h ctype.h errno.h fcntl.h float.h inttypes.h limits.h locale.h math.h pthread.h setjmp.h signal.h stdarg.h stdbool.h stddef.h stdint.h stdio.h stdlib.h
string.h strings.h time.h unistd.h wchar.h wctype.h sys/types.h sys/stat.h sys/time.h sys/mman.h sys/socket.h sys/select.h sys/uio.h dlfcn.h poll.h sched.h
semaphore.h""".split()
# Apple-only libc headers that redefine what Cosmopolitan's locale.h/wchar.h/... provide; their include guards are pre-defined so they become empty
neutralise = ['xlocale.h', '_xlocale.h', '__xlocale.h', '_locale.h', '_locale_posix2008.h', '_mb_cur_max.h']
neutral_guards = []
for h in neutralise:
    f = os.path.join(sdk, 'usr/include', h)
    if os.path.exists(f):
        m = re.search(r'#ifndef\s+(\w+)', open(f, errors='ignore').read())
        if m: neutral_guards.append(m.group(1))
inc = lambda h: '#if __has_include(<%s>)\n#include <%s>\n#endif' % (h, h)
lines = ['#pragma once', '/* generated by gen_compat.py */', '#ifdef __cplusplus'] + [inc(h) for h in std_headers] + ['#endif'] + [inc(h) for h in c_headers]
lines += ['/* Apple-only duplicates of Cosmopolitan libc declarations must not be read: */']
lines += [f'#ifndef {g}\n#define {g}\n#endif' for g in sorted(set(neutral_guards))]
lines += ['/* Apple headers must not redefine what Cosmopolitan just provided: */']
lines += [f'#ifndef {g}\n#define {g}\n#endif' for g in sorted(set(guards))]
lines += ['#ifndef __BEGIN_DECLS', '#ifdef __cplusplus', '#define __BEGIN_DECLS extern "C" {', '#define __END_DECLS }', '#else', '#define __BEGIN_DECLS', '#define __END_DECLS', '#endif', '#endif']
lines += ['/* NOW pretend to be Apple: nothing above (libc++, C library) may see these macros */',
          '#define __APPLE__ 1', '#define __MACH__ 1', '#ifdef __aarch64__', '#define __arm64__ 1', '#define TARGET_CPU_ARM64 1', '#else', '#define TARGET_CPU_X86_64 1', '#endif',
          '#define TARGET_OS_MAC 1', '#define TARGET_OS_OSX 1', '#define TARGET_OS_IPHONE 0', '#define TARGET_OS_SIMULATOR 0', '#define TARGET_OS_EMBEDDED 0', '#define TARGET_OS_IOS 0', '#define TARGET_OS_WIN32 0', '#define TARGET_OS_UNIX 0',
          '/* Apple\'s own <sys/cdefs.h> (Cosmopolitan\'s was found first and lacks __DARWIN_*, __ASSUME_PTR_ABI_*, __sized_by ...): read it explicitly, redefinitions are only warnings */',
          '#undef __BEGIN_DECLS', '#undef __END_DECLS', '#undef _CDEFS_H_', '#include "%s/usr/include/sys/cdefs.h"' % sdk,
          '/* things Apple\'s clang provides itself or Apple\'s headers expect from it */',
          '#define __APPLE_CC__ 6000', '#define __APPLE_CPP__ 1',
          '#ifndef __nullable\n#define __nullable _Nullable\n#endif', '#ifndef __nonnull\n#define __nonnull _Nonnull\n#endif', '#ifndef __null_unspecified\n#define __null_unspecified _Null_unspecified\n#endif', '#ifndef __nullable_result\n#define __nullable_result _Nullable_result\n#endif',
          '/* a typedef Cosmopolitan has under the same name with another type */', '#define syscall_arg_t apple_syscall_arg_t',
          '/* Carbon\'s fp.h redeclares scalb() and defines isnan/isfinite/signbit/fpclassify as macros, which breaks std::isnan & co */', '#define __FP__ 1']
open(out, 'w').write('\n'.join(lines) + '\n')
print(f'{len(set(guards))} guards predefined; skipped headers: {" ".join(skipped)}')
print('kept (Apple definitions used):', ' '.join(kept[:80]))
