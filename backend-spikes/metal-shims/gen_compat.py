#!/usr/bin/env python3
"""Generate cosmo_apple_compat.h for compiling Apple-SDK-dependent code (Dawn's Metal backend) with the Cosmopolitan toolchain.
Cosmopolitan supplies the C library (stdint.h, stddef.h, sys/types.h ... with Linux-style typedefs: uint64_t is unsigned long). Apple's SDK headers redefine the same
public types differently (unsigned long long), which would make Dawn's symbols mangle differently in these translation units than in the rest of Dawn. So: parse the
SDK's one-typedef-per-file headers in usr/include/sys/_types/, and pre-define the include guard of every header whose public typedef Cosmopolitan already provides.
usage: gen_compat.py <sdk-path> <out.h>"""
import re, sys, os, glob
sdk, out = sys.argv[1], sys.argv[2]
cosmo_has = set('''int8_t int16_t int32_t int64_t uint8_t uint16_t uint32_t uint64_t intptr_t uintptr_t intmax_t uintmax_t size_t ssize_t off_t wchar_t ptrdiff_t time_t clock_t
pid_t uid_t gid_t mode_t dev_t ino_t nlink_t useconds_t suseconds_t socklen_t blkcnt_t blksize_t fsblkcnt_t fsfilcnt_t id_t key_t u_int8_t u_int16_t u_int32_t u_int64_t
va_list sigset_t wint_t wctype_t rsize_t errno_t timespec timeval fd_set pthread_t pthread_attr_t pthread_mutex_t pthread_mutexattr_t pthread_cond_t pthread_condattr_t
pthread_key_t pthread_once_t pthread_rwlock_t pthread_rwlockattr_t FILE fpos_t mbstate_t max_align_t'''.split())
guards, skipped, kept = [], [], []
for f in sorted(glob.glob(os.path.join(sdk, 'usr/include/sys/_types/_*.h'))):
    t = open(f, errors='ignore').read()
    g = re.search(r'#ifndef\s+(\w+)', t)
    names = set(re.findall(r'typedef\b[^;{}]*?\b(\w+)\s*;', t))
    names |= set(re.findall(r'\bstruct\s+(\w+)\s*\{', t))
    if g and names & cosmo_has:
        guards.append(g.group(1)); skipped.append(os.path.basename(f))
    else:
        kept.append(os.path.basename(f))
lines = ['#pragma once',
         '/* generated by gen_compat.py */',
         '#ifdef __cplusplus',
         '#include <cstdint>', '#include <cstddef>', '#include <cstdlib>', '#include <cstring>', '#include <cstdio>', '#include <cmath>', '#include <climits>', '#include <ctime>',
         '#include <cerrno>', '#include <cstdarg>', '#include <cwchar>', '#include <cctype>', '#include <vector>', '#include <string>', '#include <memory>', '#include <mutex>',
         '#include <atomic>', '#include <functional>', '#include <algorithm>', '#include <array>', '#include <unordered_map>', '#include <map>', '#include <set>',
         '#include <optional>', '#include <variant>', '#include <utility>', '#include <thread>', '#include <condition_variable>',
         '#endif',
         '#include <stdint.h>', '#include <stddef.h>', '#include <stdbool.h>', '#include <stdlib.h>', '#include <string.h>', '#include <stdio.h>', '#include <sys/types.h>',
         '#include <unistd.h>', '#include <pthread.h>', '#include <time.h>', '#include <errno.h>', '#include <limits.h>', '#include <math.h>', '#include <stdarg.h>',
         '#include <wchar.h>', '#include <signal.h>', '#include <setjmp.h>', '#include <inttypes.h>',
         '/* Apple headers must not redefine what Cosmopolitan just provided: */']
lines += [f'#ifndef {g}\n#define {g}\n#endif' for g in sorted(set(guards))]
lines += ['#ifndef __BEGIN_DECLS', '#ifdef __cplusplus', '#define __BEGIN_DECLS extern "C" {', '#define __END_DECLS }', '#else', '#define __BEGIN_DECLS', '#define __END_DECLS', '#endif', '#endif']
open(out, 'w').write('\n'.join(lines) + '\n')
print(f'{len(set(guards))} guards predefined; skipped headers: {" ".join(skipped)}')
print('kept (Apple definitions used):', ' '.join(kept[:80]))
